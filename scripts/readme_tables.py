"""Markdown tables for the README / docs from results/summary.json -> docs/results_tables.md.
Refuses (exit 2) a summary that does not cover the full grid."""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from aran import scenarios as S

LABEL = {"fixed": "Fixed MCS (dev-best)", "cqi-only": "CQI only (inner loop)", "olla-10": "OLLA, 10% target",
         "olla-tuned": "OLLA, dev-tuned", "olla-tuned-backoff": "OLLA dev-tuned + power back-off rule",
         "genie": "Genie MCS (non-causal, full power)", "sa": "Single-agent DQN", "iql": "IQL, own reward",
         "iql_team": "IQL, team reward", "vdn": "VDN, team reward (cooperative)"}


def fmt(x, ci, nd=3):
    return f"{x:.{nd}f} [{ci[0]:.{nd}f}, {ci[1]:.{nd}f}]"


def tables(summ):
    out = []
    for sc, v in summ["scenarios"].items():
        out.append(f"#### Scenario `{sc}`\n")
        out.append("| Method | SE (bit/s/Hz/cell) | Edge UE thr. | Jain | BLER | Power back-off (dB) | I/N (dB) |")
        out.append("|---|---|---|---|---|---|---|")
        for m, k in v["methods"].items():
            out.append(f"| {LABEL[m]} | {fmt(k['se']['mean'], k['se']['ci'])} | {fmt(k['edge']['mean'], k['edge']['ci'])} | "
                       f"{fmt(k['jain']['mean'], k['jain']['ci'])} | {fmt(k['bler']['mean'], k['bler']['ci'])} | "
                       f"{fmt(k['power_db']['mean'], k['power_db']['ci'], 2)} | {fmt(k['inr_db']['mean'], k['inr_db']['ci'], 1)} |")
        out.append("")
    out.append(f"#### Pre-registered comparisons (one Holm family of {summ['holm_family_size']})\n")
    out.append("| Scenario | A - B | Metric | Diff [95% CI] | Rel. | Unit (n) | A>B / A<B | p | Holm p | Sig. |")
    out.append("|---|---|---|---|---|---|---|---|---|---|")
    for c in summ["comparisons"]:
        out.append(f"| {c['scenario']} | {LABEL[c['a']]} - {LABEL[c['b']]} | {c['metric']} | {fmt(c['diff'], c['ci'])} | "
                   f"{c['rel_pct']:+.1f}% | {c['unit']} ({c['n']}) | {c['wins']}/{c['losses']} | {c['p']:.2g} | {c['p_holm']:.2g} | "
                   f"{'yes' if c['significant'] else 'no'} |")
    return "\n".join(out) + "\n"


def main():
    path = os.path.join(ROOT, "results/summary.json")
    s = json.load(open(path))
    if s.get("grid", {}).get("seeds") != list(S.SEEDS) or set(s.get("scenarios", {})) != set(S.SCENARIOS) or \
            any(set(v["methods"]) != set(LABEL) for v in s["scenarios"].values()):
        print("refusing: summary.json does not cover the full grid", file=sys.stderr)
        return 2
    open(os.path.join(ROOT, "docs/results_tables.md"), "w").write(
        "<!-- generated by scripts/readme_tables.py from results/summary.json; do not edit -->\n\n" + tables(s))
    print("wrote docs/results_tables.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
